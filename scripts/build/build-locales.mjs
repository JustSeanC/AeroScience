import {readFileSync, writeFileSync, readdirSync, mkdirSync} from 'node:fs';
import {resolve, dirname} from 'node:path';
import {fileURLToPath} from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const folder = resolve(root, 'src/AeroScience.Engine/wwwroot/i18n');
const read = path => JSON.parse(readFileSync(path, 'utf8'));
const placeholders = text => [...text.matchAll(/\{([a-z][a-zA-Z0-9]*)\}/g)].map(match => match[1]).sort();
const same = (a,b) => JSON.stringify([...new Set(a)].sort()) === JSON.stringify([...new Set(b)].sort());

export function validateCatalogs({manifest, schema, catalogs}) {
  const failures = [], require = (ok, reason) => {if (!ok) failures.push(reason);};
  const approved = ['en-US','es-ES','fr-FR','de-DE','pt-BR'];
  require(manifest.version === 1 && schema.version === 1, 'Unsupported message/manifest schema version.');
  require(manifest.fallback === 'en-US', 'English must remain the fallback.');
  require(same(manifest.locales.map(locale => locale.id),approved) && manifest.locales.length === approved.length,
    'The five approved locale identities must be unique and unchanged.');
  require(manifest.locales.every(locale => locale.name && ['ltr','rtl'].includes(locale.direction) && ['source','preview','reviewed'].includes(locale.review)), 'Locale name/direction/review status required.');
  require(!!catalogs['en-US'], 'Missing canonical English catalog.');
  for (const [key,rule] of Object.entries(schema.messages)) {
    require(/^[a-z][a-zA-Z0-9]*(\.[a-zA-Z][a-zA-Z0-9]*)+$/.test(key), 'Invalid semantic key: '+key);
    require(typeof rule.context === 'string' && rule.context.length > 0 && Array.isArray(rule.parameters), 'Missing translation context/parameters: '+key);
    require(!rule.plural || rule.parameters.includes(rule.plural), 'Missing plural parameter: '+key);
  }
  for (const [locale,catalog] of Object.entries(catalogs)) {
    const metadata = manifest.locales.find(item => item.id === locale);
    require(!!metadata, 'Unadvertised locale: '+locale);
    require(catalog.locale === locale && catalog.version === manifest.catalogVersion, 'Catalog identity/version: '+locale);
    const missing = Object.keys(schema.messages).filter(key => !Object.hasOwn(catalog.messages,key));
    require(metadata?.review === 'preview' || missing.length === 0, 'Missing keys in '+locale+': '+missing.join(', '));
    for (const [key,message] of Object.entries(catalog.messages)) {
      const rule = schema.messages[key];
      if (!rule) {failures.push('Extra key in '+locale+': '+key);continue;}
      const forms = typeof message === 'string' ? [message] : Object.values(message || {});
      require(rule.plural ? typeof message === 'object' && message !== null && Object.hasOwn(message,'one') && Object.hasOwn(message,'other')
        && Object.keys(message).every(form => ['one','other'].includes(form)) : typeof message === 'string', 'Invalid message/plural forms: '+locale+'/'+key);
      require(forms.length > 0 && forms.every(text => typeof text === 'string' && text.trim()
        && same(placeholders(text),rule.parameters) && !/[{}]/.test(text.replace(/\{[a-z][a-zA-Z0-9]*\}/g,''))), 'Invalid placeholders/empty text: '+locale+'/'+key);
    }
  }
  require(manifest.locales.every(locale => locale.review === 'preview' || !!catalogs[locale.id]), 'Reviewed locale must have a complete bundled catalog.');
  if (failures.length) throw new Error(failures.join('\n'));
  return {messages:Object.keys(schema.messages).length, locales:manifest.locales.length, bundled:Object.keys(catalogs)};
}

export function pseudoCatalog(catalog) {
  const accents = {'a':'á','e':'ë','i':'ï','o':'ö','u':'ü','A':'Á','E':'Ë','I':'Ï','O':'Ö','U':'Ü'};
  const expand = text => '［'+text.split(/(\{[a-z][a-zA-Z0-9]*\})/g).map(part => part.startsWith('{') ? part
    : part.replace(/[aeiouAEIOU]/g, letter => accents[letter])).join('')+' — '+ 'extended '.repeat(Math.max(1,Math.ceil(text.length/25)))+'］';
  return {...catalog,locale:'en-XA',messages:Object.fromEntries(Object.entries(catalog.messages)
    .map(([key,message]) => [key,typeof message === 'string' ? expand(message)
      : Object.fromEntries(Object.entries(message).map(([form,text]) => [form,expand(text)]))]))};
}

export function localeBundle() {
  return {manifest:read(resolve(folder,'locale-manifest.json')),schema:read(resolve(folder,'message-schema.json')),
    catalogs:Object.fromEntries(readdirSync(resolve(folder,'locales')).filter(name => name.endsWith('.json'))
      .sort().map(name => [name.slice(0,-5),read(resolve(folder,'locales',name))]))};
}
export function generatedModule(bundle) {
  return '// Generated by scripts/build/build-locales.mjs; edit the canonical JSON files.\n'
    +'export const localeData = '+JSON.stringify(bundle,null,2)+';\n';
}

export function nativeCatalogAssets(bundle = localeBundle()) {
  validateCatalogs(bundle);
  const formatter=readFileSync(resolve(folder,'../i18n-format.js'),'utf8').replace(/\r\n/g,'\n').replace(/^export /gm,'');
  return {
    'AeroScience.LocaleData.js':'// Generated canonical catalog; do not edit.\nvar AeroScienceLocaleData = '+JSON.stringify(bundle)+';\n',
    'AeroScience.LocaleFormat.js':'// Generated shared formatter; do not edit.\nvar AeroScienceLocaleFormat = (function(){\n'+formatter+'\nreturn {createTranslator:createTranslator,supportedLocale:supportedLocale};\n}());\n'
  };
}

export function validateReferences(schema,sources) {
  const referenced=new Set();
  for(const [name,source]of Object.entries(sources)){
    const keys=[...source.matchAll(/data-i18n(?:-aria-label|-placeholder)?="([^"]+)"/g)].map(match=>match[1]);
    if(source.includes("from './i18n.js'")){
      keys.push(...[...source.matchAll(/\bt\(\s*['"]([^'"]+)['"]\s*(?=[,)])/g)].map(match=>match[1]));
      keys.push(...[...source.matchAll(/\.i18n(?:AriaLabel|Placeholder)?\s*=\s*['"]([^'"]+)['"]/g)].map(match=>match[1]));
    }
    if(name.endsWith('navigation-routes.js'))keys.push(...[...source.matchAll(/['"](nav\.[a-zA-Z]+)['"]/g)].map(match=>match[1]));
    for(const key of keys){
      if(!Object.hasOwn(schema.messages,key))throw new Error('Undefined message reference: '+name+' / '+key);
      referenced.add(key);
    }
  }
  // State/source badge families have computed keys and P04 consumers. Report
  // unused IDs for review; do not delete their scientific terminology silently.
  return {references:referenced.size,unusedKeys:Object.keys(schema.messages).filter(key=>!referenced.has(key))};
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const bundle = localeBundle(), result = validateCatalogs(bundle);
  const web=resolve(folder,'..'),sources=Object.fromEntries(readdirSync(web).filter(name=>/\.(html|js)$/.test(name)).map(name=>[name,readFileSync(resolve(web,name),'utf8')]));
  const references=validateReferences(bundle.schema,sources);
  const target = resolve(folder,'catalog.generated.js'), content = generatedModule(bundle);
  if (process.argv.includes('--check')) {
    if (readFileSync(target,'utf8').replace(/\r\n/g,'\n') !== content) throw new Error('Stale generated locale bundle. Run node scripts/build/build-locales.mjs.');
  } else writeFileSync(target,content);
  const option = process.argv.indexOf('--output-directory');
  if (option >= 0) {
    if (!process.argv[option+1]) throw new Error('Provide an output directory.');
    const output = resolve(process.argv[option+1]);mkdirSync(output,{recursive:true});
    writeFileSync(resolve(output,'browser-catalog.js'),content);
    const assets=nativeCatalogAssets(bundle);
    for(const [name,source]of Object.entries(assets))writeFileSync(resolve(output,name),source);
    // Preserve the P02a standalone formatter API while shipping the same P02b adapter.
    writeFileSync(resolve(output,'AeroScience.I18n.js'),assets['AeroScience.LocaleFormat.js']+readFileSync(resolve(root,'msfs-toolbar/PackageSources/html_ui/InGamePanels/AeroScience/AeroScience.I18n.js'),'utf8'));
    writeFileSync(resolve(output,'catalog-bundle.json'),JSON.stringify(bundle,null,2)+'\n');
  }
  console.log(JSON.stringify({...result,references:references.references,unused:references.unusedKeys.length}));
}
